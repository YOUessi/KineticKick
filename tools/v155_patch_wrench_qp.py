#!/usr/bin/env python3
"""v155 CPU-only 35D floating-base QP with FOUR frictional corners per 6D stance.

The contact wrench is generated by corner forces; no free foot torque, fictitious
actuator, measured GRF, PhysX collision or elite human label is implied.
"""
from __future__ import annotations
import copy
import json
import math
import subprocess
from pathlib import Path

import numpy as np
import scipy.sparse as sp
import osqp

from wholebody_safety_interface_v055 import G1_JOINT_ORDER
from v154_cpu_feasibility_campaign import synthetic_problem

ROOT = Path(__file__).resolve().parents[1]
FROZEN_SHA = "6d9ff1530a77a7cd571060db85e415633f8c4dfb"
N, NA, DT = 35, 29, .005


def frozen():
    path = "configs/v155_frozen_patched_stance_wrench.json"
    committed = subprocess.check_output(["git", "-C", str(ROOT), "show", FROZEN_SHA + ":" + path])
    if committed != (ROOT / path).read_bytes():
        raise ValueError("V155_PROTOCOL_MUTATED")
    cfg = json.loads(committed)
    if cfg["parent_sha"] != "2f9a09183196c59bda3e47a527551a20a9a96c67":
        raise ValueError("V155_PARENT_SHA_DRIFT")
    if cfg["positive_cases"] != 48 or len(cfg["negative_kinds"]) != 12:
        raise ValueError("V155_MATRIX_DRIFT")
    return cfg


def a(value, shape, tag):
    z = np.asarray(value, dtype=np.float64)
    if z.shape != tuple(shape) or not np.isfinite(z).all():
        raise ValueError("V155_BAD_" + tag)
    return z


def corners(cfg):
    L = float(cfg["fixture_half_length_m"])
    W = float(cfg["fixture_half_width_m"])
    return [[-L,-W], [-L,W], [L,-W], [L,W]]


def corner_mapping(pts):
    """6D resultant wrench about sole origin: force followed by r cross force."""
    B = np.zeros((6,12))
    for j,(x,y) in enumerate(pts):
        B[:3,3*j:3*j+3] = np.eye(3)
        B[3:,3*j:3*j+3] = [[0.,0.,y],[0.,0.,-x],[-y,x,0.]]
    return B


def fixture(phase,mode,seed):
    cfg = frozen()
    if phase not in cfg["phase_order"] or mode not in cfg["supports"] or seed not in cfg["seeds"]:
        raise ValueError("V155_UNDECLARED_CASE")
    p = synthetic_problem(phase,mode,seed)
    old = p["contacts"]
    new = []
    for contact in old:
        J3 = a(contact["J"], (3,35), "ORIGINAL_J")
        J6 = np.zeros((6,35))
        J6[:3] = J3
        J6[3:6,3:6] = np.eye(3)
        new.append({"body":contact["body"], "J6":J6.tolist(),
                    "Jdotv6":[0.]*6,"mu":cfg["fixture_mu"],
                    "normal_axis":"world_z",
                    "ground_only_signed_normal":True,
                    "contact_frame":"world_aligned_flat_sole",
                    "corners_xy":corners(cfg)})
    p["contacts"] = new
    p["h"][3] = .16
    p["h"][4] = -.13
    p["sole_calibrated_for_real"] = False
    p["native_pair_claim"] = False
    return p


def validate(p):
    cfg = frozen()
    if p.get("joint_names") != list(G1_JOINT_ORDER):
        raise ValueError("V155_ORIGINAL29_ORDER")
    if p.get("source_kind") not in ("synthetic", "runtime"):
        raise ValueError("V155_SOURCE_UNKNOWN")
    if p.get("require_human_training") and p.get("provenance",{}).get("human_training_qualified") is not True:
        raise ValueError("V155_HUMAN_SUPERVISION_NOT_QUALIFIED")
    if p.get("native_pair_claim") and p.get("native_pair_manifold_verified") is not True:
        raise ValueError("V155_NATIVE_COLLISION_REPORT_MISSING")
    if p["source_kind"] == "runtime":
        keys=cfg["runtime_requirements"]
        provenance=p.get("provenance",{})
        if not all(provenance.get(k) is True for k in keys[:-1]) or not provenance.get(keys[-1]):
            raise ValueError("V155_RUNTIME_UNCERTIFIED")
        if p.get("sole_calibrated_for_real") is not True:
            raise ValueError("V155_RUNTIME_UNCALIBRATED_SOLE")
    M=a(p["M"],(35,35),"M")
    h=a(p["h"],(35,),"H")
    if np.max(np.abs(M-M.T))>1e-9 or np.linalg.eigvalsh(M).min()<=1e-9:
        raise ValueError("V155_NONSPD_M")
    for key in ("q","dq","q_lo","q_hi","dq_max","tau_max","acc_max","a_ref_joint"):
        a(p[key],(29,),key.upper())
    q=np.asarray(p["q"])
    dq=np.asarray(p["dq"])
    if np.any(np.asarray(p["q_lo"])>=np.asarray(p["q_hi"])) or np.any(q<np.asarray(p["q_lo"])) or np.any(q>np.asarray(p["q_hi"])):
        raise ValueError("V155_Q_BOUNDS")
    for key in ("dq_max","tau_max","acc_max"):
        if a(p[key],(29,),key).min()<=0:
            raise ValueError("V155_LIMIT_NONPOSITIVE")
    if np.any(np.abs(dq)>np.asarray(p["dq_max"])+1e-9):
        raise ValueError("V155_INITIAL_QDOT_UNSAFE")
    con=p.get("contacts")
    if not isinstance(con,list) or len(con) not in (1,2):
        raise ValueError("V155_MISSING_GROUND_SUPPORT")
    if len({c.get("body") for c in con}) != len(con) or any(c.get("body") not in ("left","right") for c in con):
        raise ValueError("V155_INVALID_STANCE")
    for c in con:
        a(c.get("J6"),(6,35),"J6")
        a(c.get("Jdotv6"),(6,),"JDOT6")
        z=a(c.get("corners_xy"),(4,2),"CORNERS")
        if not np.allclose(z,np.asarray(corners(cfg)),atol=1e-12,rtol=0):
            raise ValueError("V155_BAD_SOLE_PATCH_CORNERS")
        if c.get("ground_only_signed_normal") is not True:
            raise ValueError("V155_NON_GROUND_CONTACT")
        if c.get("normal_axis")!="world_z" or c.get("contact_frame")!="world_aligned_flat_sole":
            raise ValueError("V155_UNKNOWN_SOLE_FRAME")
        if type(c.get("mu")) not in (float,int) or not 0<float(c["mu"])<=2 or not math.isfinite(float(c["mu"])):
            raise ValueError("V155_BAD_FRICTION")
    gs=p.get("guards")
    if not isinstance(gs,list) or len(gs)<1:
        raise ValueError("V155_MISSING_NONFOOT_GEOMETRY")
    for g in gs:
        if g.get("pair") not in ("left_wrist_to_left_hip","right_wrist_to_right_hip","body_to_environment"):
            raise ValueError("V155_BAD_COLLIDER")
        a(g.get("distance_gradient35"),(35,),"COLLISION_GRAD")
        for name in ("signed_distance_m","min_distance_m","signed_rate_mps","acceleration_bias_mps2"):
            v=g.get(name)
            if type(v) not in (float,int) or not math.isfinite(v):
                raise ValueError("V155_MISSING_COLLIDER_NUMBERS")
        if g["min_distance_m"] < 0:
            raise ValueError("V155_BAD_GAP_MARGIN")
    return M,h


def solve(p):
    M,h=validate(p)
    cfg=frozen()
    nc=len(p["contacts"])
    dim=N+NA+12*nc
    rows=[]; lo=[]; hi=[]
    def add(r,L,U):
        rows.append(r);lo.append(L);hi.append(U)
    J=np.vstack([a(c["J6"],(6,35),"J") for c in p["contacts"]])
    JD=np.concatenate([a(c["Jdotv6"],(6,),"JD") for c in p["contacts"]])
    B=sp.block_diag([corner_mapping(a(c["corners_xy"],(4,2),"PTS")) for c in p["contacts"]]).toarray()
    JT_B=J.T@B
    for i in range(35):
        r=np.zeros(dim);r[:35]=M[i]
        if i>=6:r[35+i-6]=-1
        r[64:]=-JT_B[i]
        add(r,-h[i],-h[i])
    for i in range(6*nc):
        r=np.zeros(dim);r[:35]=J[i]
        add(r,-JD[i],-JD[i])
    q=a(p["q"],(29,),"Q")
    dq=a(p["dq"],(29,),"DQ")
    v=a(p["dq_max"],(29,),"V")
    qlo=a(p["q_lo"],(29,),"LO")
    qhi=a(p["q_hi"],(29,),"HI")
    al=a(p["acc_max"],(29,),"A")
    tl=a(p["tau_max"],(29,),"T")
    for j in range(29):
        L=max(-al[j],(-v[j]-dq[j])/DT, 2*(qlo[j]-q[j]-DT*dq[j])/DT**2)
        U=min(al[j],(v[j]-dq[j])/DT, 2*(qhi[j]-q[j]-DT*dq[j])/DT**2)
        r=np.zeros(dim);r[6+j]=1;add(r,L,U)
        r=np.zeros(dim);r[35+j]=1;add(r,-tl[j],tl[j])
    for foot,c in enumerate(p["contacts"]):
        for k in range(4):
            base=64+12*foot+3*k
            r=np.zeros(dim);r[base+2]=1;add(r,0,np.inf)
            for axis in (0,1):
                for sign in (-1,1):
                    r=np.zeros(dim);r[base+axis]=sign;r[base+2]=-c["mu"]
                    add(r,-np.inf,0)
    for g in p["guards"]:
        grad=a(g["distance_gradient35"],(35,),"GAP")
        low=2*(g["min_distance_m"]-g["signed_distance_m"]-DT*g["signed_rate_mps"])/DT**2 - g["acceleration_bias_mps2"]
        r=np.zeros(dim);r[:35]=grad;add(r,low,np.inf)
    weights=np.concatenate([np.full(6,12.),np.full(29,4.),np.full(29,.002),np.full(12*nc,.002)])
    desired=np.zeros(dim);desired[6:35]=a(p["a_ref_joint"],(29,),"REF")
    solver=osqp.OSQP()
    solver.setup(P=sp.diags(2*weights,format="csc"),q=-2*weights*desired,
        A=sp.csc_matrix(np.vstack(rows)),l=np.asarray(lo),u=np.asarray(hi),
        verbose=False,polish=True,eps_abs=1e-7,eps_rel=1e-7,max_iter=10000,adaptive_rho=False)
    r=solver.solve()
    ok=r.info.status=="solved" and r.x is not None and np.isfinite(r.x).all()
    out={"solved":bool(ok),"status":r.info.status,"phase":p["phase"],"seed":p["seed"],
         "support":[c["body"] for c in p["contacts"]],
         "source_kind":p["source_kind"],"frozen_sha":FROZEN_SHA,
         "real_physics_episode":False,"legal_high_speed_instep_success":None,
         "human_elite_technique_learned":False,
         "native_collision_manifold_certified":False,
         "original_g1_29_joint_order":list(G1_JOINT_ORDER)}
    if ok:
        x=np.asarray(r.x)
        ff=x[64:].reshape(nc,4,3)
        out.update({"a35":x[:35].tolist(),"tau29":x[35:64].tolist(),
                   "corner_forces3":ff.tolist(),
                   "wrenches6":[(corner_mapping(np.asarray(c["corners_xy"]))@f.reshape(12)).tolist()
                               for c,f in zip(p["contacts"],ff)],
                   "objective":float(r.info.obj_val)})
    return out
